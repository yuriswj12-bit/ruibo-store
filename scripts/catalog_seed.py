def norm(value: str) -> str:
    return "".join(ch for ch in value.upper() if ch.isalnum())

def q(value: str) -> str:
    return value.replace("'", "''")

merged: dict[str, dict] = {}
for sku, vehicle, line, oes in ROWS:
    row = merged.setdefault(sku, {"vehicle": vehicle, "line": line, "oes": []})
    for oe in oes:
        if oe not in row["oes"]:
            row["oes"].append(oe)

