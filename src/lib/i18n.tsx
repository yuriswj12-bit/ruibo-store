const SPEC_KEYS: Record<string, Key> = {
  line: "specLine",
  vehicle: "specVehicle",
  sensor: "specSensor",
};

function fill(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}

const LocaleContext = createContext<{
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
} | null>(null);

function isLang(value: string | null): value is Lang {
  return value === "zh" || value === "en" || value === "es" || value === "pt";
}

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(DEFAULT_LANG);

  useEffect(() => {
    const saved = localStorage.getItem("fc-lang");
    if (isLang(saved)) setLangState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  }, [lang]);

  function setLang(next: Lang) {
    setLangState(next);
    localStorage.setItem("fc-lang", next);
  }

  function t(key: Key, vars?: Record<string, string | number>) {
    return fill(DICT[lang][key], vars);
  }

  return <LocaleContext.Provider value={{ lang, setLang, t }}>{children}</LocaleContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error("useI18n must be used inside LocaleProvider");
  return ctx;
}

export function vehicleLabel(lang: Lang, vehicle: string) {
  return VEHICLES[vehicle]?.[lang] ?? vehicle;
}

export function sensorTitle(lang: Lang, vehicle: string, sku: string) {
  const name = vehicleLabel(lang, vehicle);
  if (lang === "zh") return `${name}氧传感器 ${sku}`;
  if (lang === "es") return `Sensor de oxígeno ${name} ${sku}`;
  if (lang === "pt") return `Sensor de oxigénio ${name} ${sku}`;
  return `${name} oxygen sensor ${sku}`;
}

export function specText(lang: Lang, key: string) {
  const dictKey = SPEC_KEYS[key];
  return dictKey ? DICT[lang][dictKey] : key.replace(/_/g, " ");
}

export function specValue(lang: Lang, key: string, value: string) {
  if (key === "vehicle") return vehicleLabel(lang, value);
  if (key === "line" && value === "Automotive") return DICT[lang].lineAutomotive;
  if (key === "sensor" && value === "Heated zirconia") return DICT[lang].sensorHeated;
  if (value === "Factory quote") return DICT[lang].factoryQuote;
  return value;
}

export function moneyLabel(lang: Lang, value: string | null) {
  if (!value || value === "Factory quote") return DICT[lang].factoryQuote;
  return value;
}
